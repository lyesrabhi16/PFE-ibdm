class EmailScheduleForm extends StatefulWidget {
  EmailScheduleForm({
    super.key,
    this.showIdField = false,
    this.onValuesChanged,
    this.editable = true,
    this.schedule,
    this.showNextRunTime = false,
    this.formKey,
  });

  final bool editable;
  final EmailSchedule? schedule;
  final Key? formKey;
  final Function({
    RapportEnum? rapport,
    String? tempsEnvoi,
    IntervalEnum? interval,
    int? intervalManual,
    DateTime? nextRunTime,
    List<Role>? roles,
    List<User>? users,
    GlobalKey<FormState>? formKey,
  })? onValuesChanged;

  final bool showIdField;
  bool showNextRunTime;

  @override
  State<EmailScheduleForm> createState() => _EmailScheduleFormState();
}

class _EmailScheduleFormState extends State<EmailScheduleForm> {
  final _formKey = GlobalKey<ShadFormState>();

  Function? _getContext;

  BuildContext get getContext => _getContext!.call()!;

  ColorScheme get colorScheme => Theme.of(getContext).colorScheme;

  _valuesChanged() {
    if (!widget.editable) return;
    printMessage("interval: ${interval!.value}");
    printMessage("nextRunTime: ${nextRunTime}");
    widget.onValuesChanged?.call(
      rapport: rapport,
      tempsEnvoi:
          "${tempsEnvoi!.hour}:${tempsEnvoi!.minute}:${tempsEnvoi!.second}",
      interval: interval!.value,
      intervalManual: int.tryParse(intervalManualController.text),
      nextRunTime: nextRunTime,
      roles: sendToRoles.toList(),
      users: sendToUsers.toList(),
    );
  }

  final idController = TextEditingController();

  RapportEnum? rapport;

  ShadTimeOfDay? tempsEnvoi;

  Rx<IntervalEnum>? interval;

  final intervalManualController = TextEditingController(text: "1");

  DateTime? nextRunTime;

  final sendToRoles = <Role>[];

  final sendToUsers = <User>[];

  bool enabled = true;

  late final strings = getTranslations(getContext).obs;

  final userController = Get.find<UserController>();

  IbdmApiClient? api;

  List<User> _users = [];

  List<RapportEnum> _rapportValues = [];

  RxBool loaded = false.obs;

  final RxBool _showNextRunTime = false.obs;

  final RxBool _searchInUsers = false.obs;
  final RxBool _searchInRoles = false.obs;
  final RxList<User> _searchResultsUsers = <User>[].obs;
  final RxList<Role> _searchResultsRoles = <Role>[].obs;

  _loadUsers() async {
    final strings = getTranslations(getContext);
    try {
      final res = await api!.getUsers(
        enablePagination: false,
      );
      _users = res.data;
    } catch (e) {
      logger.e("Failed to load users : $e");
      Toasts.showErrorToast(
          context: getContext, message: strings.failedToLoadUsers);
      Navigator.of(getContext).pop();
    }
  }

  Future<void> load() async {
    if (loaded.value) {
      loaded.value = false;
    }
    final strings = getTranslations(getContext);
    idController.text = strings.autoGenerated;
    api ??= await ApiClientInstance.getApiClient();
    await _loadUsers();

    _rapportValues =
        RapportEnum.values.where((r) => r != RapportEnum.$unknown).toList();
    // await _loadPossibleMonitorValues();
    _showNextRunTime.value = widget.showNextRunTime;
    if (widget.schedule != null) {
      idController.text = widget.schedule!.id.toString();
      rapport = widget.schedule!.rapport;
      final tempsEnvoiIntList = widget.schedule!.tempsEnvoi
          .split(":")
          .map((s) => int.tryParse(s) ?? 0)
          .toList();
      tempsEnvoi = ShadTimeOfDay(
        hour: tempsEnvoiIntList[0],
        minute: tempsEnvoiIntList[1],
        second: 0,
      );
      interval = (widget.schedule!.interval).obs;
      intervalManualController.text =
          widget.schedule!.intervalManual.toString();
      nextRunTime = widget.schedule!.nextRunTime;
      sendToRoles.addAll(
        userController.roles.where(
            (role) => widget.schedule!.scheduledRoles.contains(role.roleId)),
      );
      sendToUsers.addAll(
        _users.where(
            (user) => widget.schedule!.scheduledUsers.contains(user.email)),
      );
    }
    interval ??= (IntervalEnum.jour).obs;
    rapport ??= RapportEnum.values.first;
    tempsEnvoi ??= ShadTimeOfDay(
      hour: DateTime.now().hour,
      minute: DateTime.now().minute,
      second: 0,
    );
    loaded.value = true;
  }

  @override
  Widget build(BuildContext context) {
    _getContext = () => context;
    return Obx(() {
      if (!loaded.value) {
        load();
        return SizedBox(
          height: AppSizes.lg * 10,
          child: CircularProgressIndicatorWithText(
            text: strings.value.loading,
          ),
        );
      }
      _valuesChanged();
      return ShadForm(
          onChanged: _valuesChanged,
          key: _formKey,
          autovalidateMode: ShadAutovalidateMode.alwaysAfterFirstValidation,
          child: Obx(() {
            return Column(
              children: [
                SizedBox(height: AppSizes.lg),
                if (widget.showIdField)
                  ShadInputFormField(
                    enabled: widget.editable,
                    controller: idController,
                    label: Text(strings.value.id),
                  ),
                SizedBox(height: AppSizes.sm),
                Container(
                  constraints: BoxConstraints(
                    minWidth: context.width,
                  ),
                  child: ShadSelectFormField<RapportEnum>(
                    enabled: widget.editable,
                    validator: FormBuilderValidators.required(
                        errorText: strings.value.selectAReport),
                    label: Text(strings.value.rapport),
                    options: _rapportValues.map(
                      (value) => ShadOption(
                        value: value,
                        child: Text(value.json ?? strings.value.unknown),
                      ),
                    ),
                    selectedOptionBuilder: (context, value) => Container(
                        constraints: BoxConstraints(
                          minWidth: context.width,
                        ),
                        child: Text(value.json ?? strings.value.unknown)),
                    initialValue: widget.schedule?.rapport ?? rapport,
                    onChanged: (v) {
                      rapport = v;
                      _valuesChanged();
                    },
                    placeholder: Container(
                        constraints: BoxConstraints(
                          minWidth: context.width,
                        ),
                        child: Text(strings.value.selectAReport)),
                  ),
                ),
                SizedBox(height: AppSizes.sm),
                Container(
                  constraints: BoxConstraints(
                    minWidth: context.width,
                  ),
                  child: ShadSelectFormField<IntervalEnum>(
                    enabled: widget.editable,
                    validator: FormBuilderValidators.required(
                        errorText: strings.value.selectAnInterval),
                    label: Text(strings.value.interval),
                    options: IntervalEnum.values
                        .where((i) => i != IntervalEnum.$unknown)
                        .map(
                          (value) => ShadOption(
                            value: value,
                            child: Text(value.json ?? strings.value.unknown),
                          ),
                        ),
                    selectedOptionBuilder: (context, value) => Container(
                        constraints: BoxConstraints(
                          minWidth: context.width,
                        ),
                        child: Text(value.json ?? strings.value.unknown)),
                    initialValue: widget.schedule?.interval ?? interval?.value,
                    onChanged: (v) {
                      printMessage("set interval: $v");
                      interval!.value = v!;
                      printMessage("interval set: ${interval!.value}");
                      _valuesChanged();
                    },
                    placeholder: Container(
                        constraints: BoxConstraints(
                          minWidth: context.width,
                        ),
                        child: Text(strings.value.selectAnInterval)),
                  ),
                ),
                SizedBox(height: AppSizes.sm),
                if (interval!.value == IntervalEnum.manual)
                  ShadInputFormField(
                    enabled: widget.editable,
                    controller: intervalManualController,
                    label: Text(strings.value.intervalManualLabel),
                    keyboardType: TextInputType.number,
                    initialValue: "1",
                    onChanged: (v) => {
                      _valuesChanged(),
                    },
                  ),
                SizedBox(height: AppSizes.sm),
                ShadTimePickerFormField(
                  enabled: widget.editable,
                  label: Text(strings.value.tempsEnvoi),
                  maxSecond: 0,
                  initialValue: tempsEnvoi!,
                  onChanged: (v) => {
                    tempsEnvoi = v,
                    _valuesChanged(),
                  },
                ),
                SizedBox(height: AppSizes.sm),

                // tab panes to send based on users or roles
                ShadTabs(
                    value: widget.schedule != null
                        ? widget.schedule!.scheduledRoles.isNotEmpty
                            ? strings.value.roles
                            : strings.value.users
                        : strings.value.roles,
                    tabs: [
                      ShadTab(
                        value: strings.value.roles,
                        //validator: (v) =>
                        //    AppValidators.roleSelectionValidator(v?.name),
                        content: ShadCard(
                          child: Column(
                            children: [
                              Text(strings.value.sendThisAlertToRoles),
                              SizedBox(height: AppSizes.sm),
                              ShadSelect<Role>.multipleWithSearch(
                                onSearchChanged: (value) {
                                  _searchInRoles.value = false;
                                  if (value.isNotEmpty) {
                                    _searchInRoles.value = true;
                                    _searchResultsRoles.value = userController
                                        .roles
                                        .where(
                                            (role) => searchRoles(role, value))
                                        .toList();
                                  }
                                },
                                enabled: widget.editable,
                                closeOnSelect: false,
                                onChanged: (v) {
                                  sendToRoles.clear();
                                  sendToRoles.addAll(v);
                                  _valuesChanged();
                                },
                                anchor: ShadAnchorAuto(
                                  preferBelow: false,
                                ),
                                options: (_searchInRoles.value
                                        ? _searchResultsRoles
                                        : userController.roles)
                                    .map(
                                  (r) => ShadOption(
                                    value: r,
                                    child: Text(r.name,
                                        style: Theme.of(context)
                                            .textTheme
                                            .bodyMedium
                                            ?.copyWith(
                                              color: AppColors
                                                  .getRoleColorWithRole(r),
                                            )),
                                  ),
                                ),
                                selectedOptionsBuilder: (context, values) =>
                                    Container(
                                  constraints: BoxConstraints(
                                    minWidth: context.width,
                                  ),
                                  child: Column(
                                    children: values
                                        .map((role) => Text(
                                              role.name,
                                              style: Theme.of(context)
                                                  .textTheme
                                                  .bodyMedium
                                                  ?.copyWith(
                                                    color: AppColors
                                                        .getRoleColorWithRole(
                                                            role),
                                                  ),
                                            ))
                                        .toList(),
                                  ),
                                ),
                                initialValues: sendToRoles,
                                placeholder: Container(
                                    constraints: BoxConstraints(
                                      minWidth: context.width,
                                    ),
                                    child: Text(strings.value.selectRoles)),
                              ),
                            ],
                          ),
                        ),
                        child: Text(strings.value.roles),
                      ),
                      ShadTab(
                          value: strings.value.users,
                          content: ShadCard(
                            child: Column(
                              children: [
                                Text(strings.value.sendThisAlertToUsers),
                                SizedBox(height: AppSizes.sm),
                                ShadSelect<User>.multipleWithSearch(
                                  onSearchChanged: (value) {
                                    _searchInUsers.value = false;
                                    if (value.isNotEmpty) {
                                      _searchInUsers.value = true;
                                      _searchResultsUsers.value = _users
                                          .where((element) =>
                                              searchUsers(element, value))
                                          .toList();
                                    }
                                  },
                                  enabled: widget.editable,
                                  onChanged: (v) {
                                    sendToUsers.clear();
                                    sendToUsers.addAll(v);
                                    _valuesChanged();
                                  },
                                  closeOnSelect: false,
                                  anchor: ShadAnchorAuto(
                                    preferBelow: false,
                                  ),
                                  options: (_searchInUsers.value
                                          ? _searchResultsUsers
                                          : _users)
                                      .map(
                                    (user) => ShadOption(
                                      value: user,
                                      child: Text(getUserName(user),
                                          style: Theme.of(context)
                                              .textTheme
                                              .bodyMedium
                                              ?.copyWith(
                                                color: AppColors
                                                    .getRoleColorWithRoleValue(
                                                        user.role),
                                              )),
                                    ),
                                  ),
                                  selectedOptionsBuilder: (context, values) =>
                                      Container(
                                    constraints: BoxConstraints(
                                      minWidth: context.width,
                                    ),
                                    child: Column(
                                      children: values
                                          .map((user) => Text(
                                                getUserName(user),
                                                style: Theme.of(context)
                                                    .textTheme
                                                    .bodyMedium
                                                    ?.copyWith(
                                                      color: AppColors
                                                          .getRoleColorWithRoleValue(
                                                              user.role),
                                                    ),
                                              ))
                                          .toList(),
                                    ),
                                  ),
                                  initialValues: sendToUsers,
                                  placeholder: Container(
                                      constraints: BoxConstraints(
                                        minWidth: context.width,
                                      ),
                                      child: Text(strings.value.selectUsers)),
                                ),
                              ],
                            ),
                          ),
                          child: Text(strings.value.users)),
                    ]),
                SizedBox(height: AppSizes.sm),
                if (widget.editable)
                  ShadSwitchFormField(
                    enabled: widget.editable,
                    inputLabel: Text(strings.value.scheduleManually),
                    initialValue: _showNextRunTime.value,
                    onChanged: (v) => {
                      _showNextRunTime.value = v,
                    },
                  ),
                SizedBox(height: AppSizes.sm),
                if (!widget.editable || _showNextRunTime.value)
                  Row(
                    children: [
                      Container(
                        constraints: BoxConstraints(
                          maxWidth: 200,
                        ),
                        child: ShadDatePickerFormField(
                          enabled: widget.editable,
                          label: Text(strings.value.nextRunTimeDate),
                          formatDate: (date) =>
                              "${date.day}/${date.month}/${date.year}",
                          initialValue:
                              widget.schedule?.nextRunTime ?? DateTime.now(),
                          onChanged: (v) => {
                            nextRunTime = DateTime(
                              v!.year,
                              v.month,
                              v.day,
                              nextRunTime?.hour ?? v.hour,
                              nextRunTime?.minute ?? v.minute,
                            ),
                            _valuesChanged(),
                          },
                        ),
                      ),
                      SizedBox(width: AppSizes.md),
                      Expanded(
                        child: ShadTimePickerFormField(
                          enabled: widget.editable,
                          label: Text(strings.value.nextRunTimeTime),
                          initialValue: ShadTimeOfDay(
                            hour: widget.schedule?.nextRunTime?.hour ??
                                DateTime.now().hour,
                            minute: widget.schedule?.nextRunTime?.minute ??
                                DateTime.now().minute,
                            second: 0,
                          ),
                          maxSecond: 0,
                          onChanged: (v) => {
                            if (v != null)
                              {
                                nextRunTime = DateTime(
                                  nextRunTime!.year,
                                  nextRunTime!.month,
                                  nextRunTime!.day,
                                  v.hour,
                                  v.minute,
                                ),
                              },
                            _valuesChanged(),
                          },
                        ),
                      ),
                    ],
                  ),
              ],
            );
          }));
    });
  }
}
