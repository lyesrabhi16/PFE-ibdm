class SentEmailForm extends StatefulWidget {
  const SentEmailForm({
    super.key,
    this.showIdField = false,
    this.onValuesChanged,
    this.editable = true,
    this.sent,
    this.schedule,
    this.alert,
  });

  final bool editable;
  final SentEmail? sent;

  final Function({
    String? tempsEnvoi,
    String? receptionist,
    String? schedule,
    String? alert,
    bool? enabled,
  })? onValuesChanged;

  final bool showIdField;
  final EmailSchedule? schedule;
  final AlertEmail? alert;

  @override
  State<SentEmailForm> createState() => _SentEmailFormState();
}

class _SentEmailFormState extends State<SentEmailForm> {
  Function? _getContext;

  BuildContext get getContext => _getContext!.call()!;

  ColorScheme get colorScheme => Theme.of(getContext).colorScheme;

  _valuesChanged() {
    if (!widget.editable) return;
    printMessage("tempenvoiController.text ${tempenvoiController.text}");
    printMessage("receptionistController.text ${receptionistController.text}");
    printMessage("scheduleController.text ${scheduleController.text}");
    printMessage("alertController.text ${alertController.text}");
    printMessage("enabled $enabled");
    widget.onValuesChanged?.call(
      tempsEnvoi: tempenvoiController.text,
      receptionist: scheduleController.text,
      schedule: receptionistController.text,
      alert: alertController.text,
      enabled: enabled,
    );
  }

  final idController = TextEditingController();

  final tempenvoiController = TextEditingController();

  final scheduleController = TextEditingController(text: "1");

  final receptionistController =
      TextEditingController(text: "exemple@gmail.com");

  final alertController = TextEditingController(text: "7");

  bool enabled = true;

  late final strings = getTranslations(getContext).obs;

  final userController = Get.find<UserController>();

  IbdmApiClient? api;

  RxBool loaded = false.obs;

  final _formKey = GlobalKey<ShadFormState>();

  Future<void> load() async {
    if (loaded.value) {
      loaded.value = false;
    }
    final strings = getTranslations(getContext);
    idController.text = strings.autoGenerated;

    api ??= await ApiClientInstance.getApiClient();

    if (widget.sent != null) {
      idController.text = widget.sent!.id.toString();
      receptionistController.text = widget.sent!.receptionist.toString();
      scheduleController.text = widget.sent!.schedule.toString();
      alertController.text = widget.sent!.alert.toString();
      //enabled = sent!.enabled;
      tempenvoiController.text = widget.sent!.tempsEnvoi.toString();
    }

    loaded.value = true;
  }

  @override
  Widget build(BuildContext context) {
    _getContext = () => context;
    return Obx(() {
      if (!loaded.value) {
        load();
        return SizedBox(
          height: AppSizes.lg * 10,
          child: Center(
            child: CircularProgressIndicator(),
          ),
        );
      }

      return ShadForm(
          onChanged: _valuesChanged,
          child: Column(
            children: [
              SizedBox(height: AppSizes.lg),
              if (widget.showIdField)
                ShadInputFormField(
                  enabled: widget.editable,
                  controller: idController,
                  label: Text(strings.value.id),
                ),
              SizedBox(height: AppSizes.sm),
              Column(
                children: [
                  Text(strings.value.tempsEnvoi),
                  ShadDatePickerFormField(
                    enabled: widget.editable,
                    label: Text(strings.value.nextRunTimeDate),
                    formatDate: (date) =>
                        "${date.day}/${date.month}/${date.year}",
                    initialValue: widget.sent?.tempsEnvoi ?? DateTime.now(),
                  ),
                  ShadTimePicker(
                    enabled: widget.editable,
                    initialValue: widget.sent?.tempsEnvoi != null
                        ? ShadTimeOfDay.fromDateTime(widget.sent!.tempsEnvoi)
                        : null,
                  )
                ],
              ),
              SizedBox(height: AppSizes.sm),
              ShadInputFormField(
                enabled: widget.editable,
                controller: receptionistController,
                label: Text(strings.value.receptionist),
                keyboardType: TextInputType.number,
                initialValue: "exemple@gmail.com",
                onChanged: (v) => {
                  _valuesChanged(),
                },
              ),
              SizedBox(height: AppSizes.sm),
              DividerWithText(
                  text: widget.schedule != null
                      ? strings.value.schedule.toUpperCase()
                      : strings.value.alert.toUpperCase()),
              widget.schedule != null
                  ? EmailScheduleForm(
                      schedule: widget.schedule,
                      editable: false,
                      showIdField: true,
                    )
                  : AlertEmailForm(
                      formKey: _formKey,
                      alert: widget.alert,
                      editable: false,
                      showIdField: true,
                    ),
              SizedBox(height: AppSizes.lg),
            ],
          ));
    });
  }
}
