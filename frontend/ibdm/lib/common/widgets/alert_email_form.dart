import 'package:ibdm/utils/helpers/localization.dart';
import 'package:ibdm/utils/helpers/logger.dart';
import 'package:ibdm/utils/helpers/user_helpers.dart';
import 'package:shadcn_ui/shadcn_ui.dart';

class AlertEmailForm extends StatefulWidget {
  const AlertEmailForm({
    super.key,
    this.showIdField = false,
    this.onValuesChanged,
    this.editable = true,
    this.alert,
    required this.formKey,
  });

  final bool editable;
  final AlertEmail? alert;

  final Function({
    String? monitoredValue,
    String? monitorType,
    String? dangerPoint,
    String? warningPoint,
    String? dangerAlertInterval,
    String? warningAlertInterval,
    List<Role>? roles,
    List<User>? users,
    String? customMessage,
    bool? enabled,
  })? onValuesChanged;

  final GlobalKey<ShadFormState> formKey;
  final bool showIdField;

  @override
  State<AlertEmailForm> createState() => _AlertEmailFormState();
}

class _AlertEmailFormState extends State<AlertEmailForm> {
  Function? _getContext;

  BuildContext get getContext => _getContext!.call()!;

  ColorScheme get colorScheme => Theme.of(getContext).colorScheme;

  _valuesChanged() {
    if (!widget.editable) return;
    printMessage(
        "monitoredValueController.text ${monitoredValueController.text}");
    printMessage("monitorTypeController.text ${monitorTypeController.text}");
    printMessage(
        "dangerAlertIntervalController.text ${dangerAlertIntervalController.text}");
    printMessage("dangerPointController.text ${dangerPointController.text}");
    printMessage(
        "warningAlertIntervalController.text ${warningAlertIntervalController.text}");
    printMessage("warningPointController.text ${warningPointController.text}");
    printMessage(
        "customMessageController.text ${customMessageController.text}");
    printMessage("sendToRoles ${sendToRoles.map((e) => e.name).join(', ')}");
    printMessage("sendToUsers ${sendToUsers.map((e) => e.email).join(', ')}");
    printMessage("enabled $enabled");
    widget.onValuesChanged?.call(
      monitoredValue: monitoredValueController.text,
      monitorType: monitorTypeController.text,
      dangerPoint: dangerPointController.text,
      warningPoint: warningPointController.text,
      dangerAlertInterval: dangerAlertIntervalController.text,
      warningAlertInterval: warningAlertIntervalController.text,
      roles: sendToRoles.toList(),
      users: sendToUsers.toList(),
      customMessage: customMessageController.text,
      enabled: enabled,
    );
  }

  final idController = TextEditingController();

  final monitoredValueController = TextEditingController();

  final monitorTypeController = TextEditingController();

  final dangerPointController = TextEditingController(text: "1000");

  final warningPointController = TextEditingController(text: "2500");

  final dangerAlertIntervalController = TextEditingController(text: "1");

  final warningAlertIntervalController = TextEditingController(text: "7");

  final customMessageController = TextEditingController(text: "");

  final sendToRoles = <Role>[];

  final sendToUsers = <User>[];

  bool enabled = true;

  final userController = Get.find<UserController>();

  IbdmApiClient? api;

  List<User> _users = [];

  List<String> _possibleMonitorValues = [];
  final RxBool _searchInMonitorValues = false.obs;
  final RxBool _searchInUsers = false.obs;
  final RxBool _searchInRoles = false.obs;

  final RxList<String> _searchResultsMonitorValues = <String>[].obs;
  final RxList<User> _searchResultsUsers = <User>[].obs;
  final RxList<Role> _searchResultsRoles = <Role>[].obs;

  RxBool loaded = false.obs;

  _loadUsers() async {
    final strings = getTranslations(getContext).obs;
    try {
      final res = await api!.getUsers(
        enablePagination: false,
      );
      _users = res.data;
    } catch (e) {
      logger.e("Failed to load users : $e");
      Toasts.showErrorToast(
          context: getContext, message: strings.value.failedToLoadUsers);
      Navigator.of(getContext).pop();
    }
  }

  Future<void> load() async {
    if (loaded.value) {
      loaded.value = false;
    }
    final strings = getTranslations(getContext);
    idController.text = strings.autoGenerated;
    api ??= await ApiClientInstance.getApiClient();
    await _loadUsers();
    await _loadPossibleMonitorValues();

    if (widget.alert != null) {
      idController.text = widget.alert!.id.toString();
      customMessageController.text = widget.alert!.customAlertMessage ?? "";
      dangerAlertIntervalController.text =
          widget.alert!.dangerReminderInterval.toString();
      dangerPointController.text = widget.alert!.dangerPoint.toString();
      warningAlertIntervalController.text =
          widget.alert!.warningReminderInterval.toString();
      warningPointController.text = widget.alert!.warningPoint.toString();
      enabled = widget.alert!.enabled!;
      monitoredValueController.text = widget.alert!.monitoredValue.json!;
      monitorTypeController.text = widget.alert!.monitorType!.json!;
      sendToRoles.addAll(
        userController.roles
            .where((role) => widget.alert!.sendToRoles.contains(role.roleId)),
      );
      sendToUsers.addAll(
        _users.where((user) => widget.alert!.sendToUsers.contains(user.email)),
      );
    }

    loaded.value = true;
  }

  @override
  Widget build(BuildContext context) {
    _getContext = () => context;
    final strings = getTranslations(context).obs;
    return Obx(() {
      if (!loaded.value) {
        load();
        return SizedBox(
          height: AppSizes.lg * 10,
          child: Center(
            child: CircularProgressIndicator(),
          ),
        );
      }
      _valuesChanged();
      return ShadForm(
          onChanged: _valuesChanged,
          key: widget.formKey,
          autovalidateMode: ShadAutovalidateMode.alwaysAfterFirstValidation,
          child: Column(
            children: [
              SizedBox(height: AppSizes.lg),
              if (widget.showIdField)
                ShadInputFormField(
                  enabled: widget.editable,
                  controller: idController,
                  label: Text(strings.value.id),
                ),
              SizedBox(height: AppSizes.sm),
              ShadTooltip(
                builder: (context) =>
                    Text(strings.value.monitoredValueDescription),
                child: Container(
                  constraints: BoxConstraints(
                    minWidth: context.width,
                  ),
                  child: ShadSelectFormField<String>.withSearch(
                    enabled: widget.editable,
                    validator: (v) => AppValidators.monitoredValueValidator(v),
                    label: Text(strings.value.monitoredValue),
                    options: _searchInMonitorValues.value
                        ? _searchResultsMonitorValues.map(
                            (value) => ShadOption(
                              value: value,
                              child: Text(value),
                            ),
                          )
                        : _possibleMonitorValues.map(
                            (value) => ShadOption(
                              value: value,
                              child: Text(value),
                            ),
                          ),
                    selectedOptionBuilder: (context, value) => Container(
                        constraints: BoxConstraints(
                          minWidth: context.width,
                        ),
                        child: Text(value)),
                    initialValue: widget.alert?.monitoredValue.json,
                    onChanged: (v) {
                      monitoredValueController.text = v!;
                      _valuesChanged();
                    },
                    placeholder: Container(
                        constraints: BoxConstraints(
                          minWidth: context.width,
                        ),
                        child: Text(strings.value.selectAValueToMonitor)),
                    onSearchChanged: (String value) {
                      _searchInMonitorValues.value = false;
                      if (value.isNotEmpty) {
                        _searchInMonitorValues.value = true;
                        _searchResultsMonitorValues.value =
                            _possibleMonitorValues
                                .where((element) => element.contains(value))
                                .toList();
                      }
                    },
                  ),
                ),
              ),
              SizedBox(height: AppSizes.sm),
              ShadTooltip(
                builder: (context) =>
                    Text(strings.value.monitorTypeDescription),
                child: Container(
                  constraints: BoxConstraints(
                    minWidth: context.width,
                  ),
                  child: ShadSelectFormField<String>(
                    enabled: widget.editable,
                    validator: FormBuilderValidators.required(
                      errorText: strings.value.requiredField,
                    ),
                    label: Text(strings.value.monitorType),
                    options: MonitorTypeEnum.values
                        .where((mt) => mt != MonitorTypeEnum.$unknown)
                        .map(
                          (value) => ShadOption(
                            value: value.json,
                            child: Text(value.json!),
                          ),
                        ),
                    selectedOptionBuilder: (context, value) => Container(
                        constraints: BoxConstraints(
                          minWidth: context.width,
                        ),
                        child: Text(value)),
                    initialValue: widget.alert?.monitorType!.json,
                    onChanged: (v) {
                      monitorTypeController.text = v!;
                      _valuesChanged();
                    },
                    placeholder: Container(
                        constraints: BoxConstraints(
                          minWidth: context.width,
                        ),
                        child: Text(strings.value.selectAMonitorType)),
                  ),
                ),
              ),
              SizedBox(height: AppSizes.sm),
              ShadInputFormField(
                enabled: widget.editable,
                controller: dangerPointController,
                validator: FormBuilderValidators.numeric(
                  errorText: strings.value.enterAValidInteger,
                ),
                label: Text(strings.value.dangerPoint),
                keyboardType: TextInputType.number,
                initialValue: "1000",
                onChanged: (v) => {
                  _valuesChanged(),
                },
              ),
              SizedBox(height: AppSizes.sm),
              ShadInputFormField(
                enabled: widget.editable,
                controller: warningPointController,
                validator: FormBuilderValidators.numeric(
                  errorText: strings.value.enterAValidInteger,
                ),
                label: Text(strings.value.warningPoint),
                keyboardType: TextInputType.number,
                initialValue: "2500",
                onChanged: (v) => {
                  _valuesChanged(),
                },
              ),
              SizedBox(height: AppSizes.sm),
              ShadTooltip(
                builder: (context) =>
                    Text(strings.value.dangerAlertIntervalDescription),
                child: ShadInputFormField(
                  enabled: widget.editable,
                  controller: dangerAlertIntervalController,
                  validator: FormBuilderValidators.compose([
                    FormBuilderValidators.integer(
                      errorText: strings.value.enterAValidInteger,
                    ),
                    FormBuilderValidators.min(
                      0,
                      errorText: strings.value.min(0),
                    ),
                  ]),
                  label: Text(strings.value.dangerAlertIntervalInDays),
                  keyboardType: TextInputType.number,
                  initialValue: "1",
                  onChanged: (v) => {
                    _valuesChanged(),
                  },
                ),
              ),
              SizedBox(height: AppSizes.sm),
              ShadTooltip(
                builder: (context) =>
                    Text(strings.value.warningAlertIntervalDescription),
                child: ShadInputFormField(
                  enabled: widget.editable,
                  controller: warningAlertIntervalController,
                  validator: FormBuilderValidators.compose([
                    FormBuilderValidators.integer(
                      errorText: strings.value.enterAValidInteger,
                    ),
                    FormBuilderValidators.min(
                      0,
                      errorText: strings.value.min(0),
                    ),
                  ]),
                  label: Text(strings.value.warningAlertIntervalInDays),
                  keyboardType: TextInputType.number,
                  initialValue: "7",
                  onChanged: (v) => {
                    _valuesChanged(),
                  },
                ),
              ),
              SizedBox(height: AppSizes.sm),
              // tab panes to send based on users or roles
              ShadTabs(
                  value: widget.alert != null
                      ? widget.alert!.sendToRoles.isNotEmpty
                          ? "roles"
                          : "users"
                      : "roles",
                  tabs: [
                    ShadTab(
                      value: "roles",
                      //validator: (v) =>
                      //  AppValidators.roleSelectionValidator(v?.name),
                      content: ShadCard(
                        child: Column(
                          children: [
                            Text(strings.value.sendThisAlertToRoles),
                            SizedBox(height: AppSizes.sm),
                            Obx(() {
                              return ShadSelect<Role>.multipleWithSearch(
                                onSearchChanged: (value) {
                                  _searchInRoles.value = false;
                                  if (value.isNotEmpty) {
                                    _searchInRoles.value = true;
                                    _searchResultsRoles.value = userController
                                        .roles
                                        .where((element) =>
                                            searchRoles(element, value))
                                        .toList();
                                  }
                                },
                                enabled: widget.editable,
                                closeOnSelect: false,
                                onChanged: (v) {
                                  sendToRoles.clear();
                                  sendToRoles.addAll(v);
                                  _valuesChanged();
                                },
                                anchor: ShadAnchorAuto(
                                  preferBelow: false,
                                ),
                                clearSearchOnClose: false,
                                options: (_searchInRoles.value
                                        ? _searchResultsRoles
                                        : userController.roles)
                                    .map(
                                  (r) => ShadOption(
                                    value: r,
                                    child: Text(r.name,
                                        style: Theme.of(context)
                                            .textTheme
                                            .bodyMedium
                                            ?.copyWith(
                                              color: AppColors
                                                  .getRoleColorWithRole(r),
                                            )),
                                  ),
                                ),
                                selectedOptionsBuilder: (context, values) =>
                                    Container(
                                  constraints: BoxConstraints(
                                    minWidth: context.width,
                                  ),
                                  child: Column(
                                    children: values
                                        .map((role) => Text(
                                              role.name,
                                              style: Theme.of(context)
                                                  .textTheme
                                                  .bodyMedium
                                                  ?.copyWith(
                                                    color: AppColors
                                                        .getRoleColorWithRole(
                                                            role),
                                                  ),
                                            ))
                                        .toList(),
                                  ),
                                ),
                                initialValues: sendToRoles,
                                placeholder: Container(
                                    constraints: BoxConstraints(
                                      minWidth: context.width,
                                    ),
                                    child: Text(strings.value.selectRoles)),
                              );
                            }),
                          ],
                        ),
                      ),
                      child: Text(strings.value.roles),
                    ),
                    ShadTab(
                        value: "users",
                        content: ShadCard(
                          child: Column(
                            children: [
                              Text(strings.value.sendThisAlertToUsers),
                              SizedBox(height: AppSizes.sm),
                              Obx(() {
                                return ShadSelect<User>.multipleWithSearch(
                                  onSearchChanged: (value) {
                                    _searchInUsers.value = false;
                                    if (value.isNotEmpty) {
                                      _searchInUsers.value = true;
                                      _searchResultsUsers.value = _users
                                          .where((element) =>
                                              searchUsers(element, value))
                                          .toList();
                                    }
                                  },
                                  enabled: widget.editable,
                                  onChanged: (v) {
                                    sendToUsers.clear();
                                    sendToUsers.addAll(v);
                                    _valuesChanged();
                                  },
                                  closeOnSelect: false,
                                  anchor: ShadAnchorAuto(
                                    preferBelow: false,
                                  ),
                                  options: (_searchInUsers.value
                                          ? _searchResultsUsers
                                          : _users)
                                      .map(
                                    (user) => ShadOption(
                                      value: user,
                                      child: Text(getUserName(user),
                                          style: Theme.of(context)
                                              .textTheme
                                              .bodyMedium
                                              ?.copyWith(
                                                color: AppColors
                                                    .getRoleColorWithRoleValue(
                                                        user.role),
                                              )),
                                    ),
                                  ),
                                  selectedOptionsBuilder: (context, values) =>
                                      Container(
                                    constraints: BoxConstraints(
                                      minWidth: context.width,
                                    ),
                                    child: Column(
                                      children: values
                                          .map((user) => Text(
                                                getUserName(user),
                                                style: Theme.of(context)
                                                    .textTheme
                                                    .bodyMedium
                                                    ?.copyWith(
                                                      color: AppColors
                                                          .getRoleColorWithRoleValue(
                                                              user.role),
                                                    ),
                                              ))
                                          .toList(),
                                    ),
                                  ),
                                  initialValues: sendToUsers,
                                  placeholder: Container(
                                      constraints: BoxConstraints(
                                        minWidth: context.width,
                                      ),
                                      child: Text(strings.value.selectUsers)),
                                );
                              }),
                            ],
                          ),
                        ),
                        child: Text(strings.value.users)),
                  ]),
              SizedBox(height: AppSizes.sm),
              ShadInputFormField(
                enabled: widget.editable,
                controller: customMessageController,
                minLines: 4,
                maxLines: 30,
                label: Text(strings.value.customMessage),
                onChanged: (v) => {
                  _valuesChanged(),
                },
              ),
              SizedBox(height: AppSizes.md),
              Row(
                mainAxisSize: MainAxisSize.max,
                mainAxisAlignment: MainAxisAlignment.end,
                children: [
                  ShadCheckboxFormField(
                    enabled: widget.editable,
                    initialValue: widget.alert?.enabled ?? true,
                    inputLabel: Text(strings.value.active),
                    onChanged: (v) {
                      enabled = v;
                      _valuesChanged();
                    },
                  ),
                ],
              ),
              SizedBox(height: AppSizes.lg),
            ],
          ));
    });
  }

  _loadPossibleMonitorValues() async {
    // load possible monitor values
    final strings = getTranslations(getContext).obs;
    try {
      final res = await api!.getPossibleMonitorValuesAlertEmails();
      _possibleMonitorValues = [
        widget.alert?.monitoredValue.json,
        ...res.allValues
      ].nonNulls.toList();
      _possibleMonitorValues.sort();
    } catch (e) {
      logger.e("Failed to load users : $e");
      Toasts.showErrorToast(
          context: getContext,
          message: strings.value.failedToLoadPossibleValuesForMonitoring);
      Navigator.of(getContext).pop();
    }
  }
}
