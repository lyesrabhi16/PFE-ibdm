seen_tags = set()
def require_level(record, level):
    return record.levelno == level
def require_tags(record, tags):
    if (record.levelno == logging.DEBUG):
        return False
    message_split = record.message.split("#")
    if len(message_split) == 1:
        return False
    tag = message_split[0]
    if tag not in seen_tags:
        print("new tag:", tag)
        seen_tags.add(tag)
    return tag in tags